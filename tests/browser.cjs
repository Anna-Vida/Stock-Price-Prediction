const { chromium } = require('@playwright/test');
const assert = require('node:assert/strict');
const fs = require('node:fs');

(async () => {
  const browser = await chromium.launch({ channel: process.env.PLAYWRIGHT_CHANNEL || 'chrome', headless: true });
  const page = await browser.newPage({ viewport: { width: 1440, height: 1050 } });
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  // Keep the test isolated from real authentication and provider availability.
  await page.route('https://cdn.jsdelivr.net/**', route => route.abort());
  await page.route('**/api/quote?*', async route => {
    const url = new URL(route.request().url());
    if (url.searchParams.get('demo') !== '1') return route.fulfill({ status: 502, contentType: 'application/json', body: JSON.stringify({ error: 'Provider unavailable (test)' }) });
    if (url.searchParams.get('symbol') === 'AAPL') await new Promise(resolve => setTimeout(resolve, 400));
    return route.continue();
  });
  await page.goto('http://127.0.0.1:5500');
  await page.locator('#errorBanner').waitFor({ state: 'visible' });
  assert.equal(await page.locator('#research').isVisible(), false);
  await page.selectOption('#dataMode', 'demo');
  await page.locator('#research').waitFor({ state: 'visible' });
  assert.equal(await page.locator('#analyticsGrid article').count(), 8);
  assert.equal(await page.locator('#backtestRows tr').count(), 3);
  assert.equal(await page.locator('#priceChart polyline').count(), 2);
  await page.click('#favoriteButton');
  await page.click('[data-view="watchlist"]');
  assert.equal(await page.locator('#watchlistGrid [data-symbol="NVDA"]').count(), 1);
  await page.click('#watchlistGrid [data-symbol="NVDA"]');
  await page.locator('#research').waitFor({ state: 'visible' });
  await page.fill('#noteText', 'Research note preserved after refresh');
  await page.click('#refreshButton');
  assert.equal(await page.inputValue('#noteText'), 'Research note preserved after refresh');
  await page.click('#notesForm button[type="submit"]');
  await page.click('#refreshButton');
  await page.locator('#research').waitFor({ state: 'visible' });
  assert.equal(await page.inputValue('#noteText'), 'Research note preserved after refresh');
  const downloadPromise = page.waitForEvent('download');
  await page.click('#exportButton');
  const download = await downloadPromise;
  assert.equal(download.suggestedFilename(), 'NVDA-demo-research.csv');
  await page.click('[data-range="252"]');
  assert.ok((await page.locator('#priceChart polyline').first().getAttribute('points')).split(' ').length > 200);
  await page.click('[data-view="markets"]');
  await page.fill('#marketFilter', 'Healthcare');
  assert.equal(await page.locator('#marketGrid button').count(), 2);
  await page.fill('#tickerInput', 'AAPL');
  await page.click('#searchForm button');
  await page.fill('#tickerInput', 'MSFT');
  await page.click('#searchForm button');
  await page.locator('#research').waitFor({ state: 'visible' });
  assert.equal(await page.locator('#stockSymbol').textContent(), 'MSFT');
  fs.mkdirSync('test-results', { recursive: true });
  await page.screenshot({ path: 'test-results/desktop.png', fullPage: true });
  await page.setViewportSize({ width: 390, height: 844 });
  assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth));
  await page.screenshot({ path: 'test-results/mobile.png', fullPage: true });
  await page.click('[data-view="models"]');
  assert.equal(await page.locator('#modelSection').isVisible(), true);
  assert.equal(await page.locator('#chartSection').isVisible(), false);
  await page.selectOption('#dataMode', 'live');
  await page.locator('#errorBanner').waitFor({ state: 'visible' });
  assert.equal(await page.locator('#research').isVisible(), false);
  assert.equal(await page.locator('#exportButton').isDisabled(), true);
  assert.deepEqual(errors, []);
  await browser.close();
  console.log('PASS: demo analytics, error states, navigation, watchlist, notes, CSV, ranges, search race, mobile layout; no browser errors.');
})().catch(error => { console.error(error); process.exit(1); });
