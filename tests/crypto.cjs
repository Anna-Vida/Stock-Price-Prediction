const { chromium } = require('@playwright/test');
const assert = require('node:assert/strict');
const fs = require('node:fs');

(async () => {
  const browser = await chromium.launch({ channel: process.env.PLAYWRIGHT_CHANNEL || 'chrome', headless: true });
  const page = await browser.newPage({ viewport: { width: 1440, height: 1000 }, reducedMotion: 'reduce' });
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  let stale = false;
  await page.route('**/api/crypto/markets?*', async route => {
    const url = new URL(route.request().url());
    if (url.searchParams.get('demo') === '1') return route.continue();
    if (!stale) return route.fulfill({ status: 502, contentType: 'application/json', body: JSON.stringify({ error: 'Provider unavailable (test)' }) });
    url.searchParams.set('demo', '1');
    const result = await route.fetch({ url: url.href });
    const body = await result.json();
    return route.fulfill({ json: { ...body, stale: true, demo: false, source: 'CoinGecko', warning: 'Cached prices (test)' } });
  });
  await page.goto('http://127.0.0.1:5500/crypto');
  await page.getByRole('alert').waitFor();
  assert.equal(await page.locator('[data-coin]').count(), 0);
  await page.getByLabel('Crypto data source').selectOption('demo');
  await page.locator('[data-coin="bitcoin"]').waitFor();
  assert.equal(await page.locator('[data-coin]').count(), 8);
  assert.equal(await page.getByText(/Synthetic demo data/).isVisible(), true);
  await page.getByRole('button', { name: 'Remove Bitcoin', exact: true }).click();
  await page.waitForFunction(() => document.querySelectorAll('[data-coin]').length === 7);
  await page.getByRole('button', { name: /Search cryptocurrencies/ }).click();
  await page.getByLabel('Search by coin name or symbol').fill('doge');
  await page.getByRole('button', { name: /Dogecoin/ }).click();
  await page.locator('[data-coin="dogecoin"]').waitFor();
  await page.getByRole('slider', { name: /Dogecoin/ }).focus();
  await page.keyboard.press('ArrowLeft');
  assert.equal(await page.locator('[data-coin="dogecoin"]').getByText(/Sample 167\/168/).isVisible(), true);
  await page.keyboard.press('Control+k');
  await page.getByRole('dialog').waitFor();
  await page.keyboard.press('Escape');
  assert.equal(await page.getByRole('dialog').count(), 0);
  await page.reload();
  await page.getByRole('alert').waitFor();
  await page.getByLabel('Crypto data source').selectOption('demo');
  await page.locator('[data-coin="dogecoin"]').waitFor();
  assert.equal(await page.locator('[data-coin="bitcoin"]').count(), 0);
  fs.mkdirSync('test-results', { recursive: true });
  await page.screenshot({ path: 'test-results/crypto-desktop.png', fullPage: true });
  await page.setViewportSize({ width: 390, height: 844 });
  assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
  await page.screenshot({ path: 'test-results/crypto-mobile.png', fullPage: true });
  stale = true;
  await page.getByLabel('Crypto data source').selectOption('live');
  await page.getByText(/Stale data:/).waitFor();
  assert.equal(await page.getByText(/Synthetic demo data/).count(), 0);
  // Persisting an empty list must not restore default selections.
  await page.evaluate(() => localStorage.setItem('predictCryptoCoins', '[]'));
  await page.reload();
  await page.getByText('Build your crypto watchlist').waitFor();
  assert.equal(await page.locator('[data-coin]').count(), 0);
  await page.getByRole('link', { name: 'Stocks', exact: true }).click();
  await page.locator('#tickerInput').waitFor();
  assert.deepEqual(errors, []);
  await browser.close();
  console.log('PASS: crypto demo, failures, search/add/remove, persistence, keyboard chart/dialog, mobile, stale labels, empty list and stock navigation.');
})().catch(error => { console.error(error); process.exit(1); });
